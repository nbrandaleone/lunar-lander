//! difficulty, and pad multipliers match the classic vector arcade layout.

/// Scale factor applied to raw terrain coordinates.
pub const LAND_SCALE: f64 = 1.5;

/// Vertical offset applied after scaling raw terrain coordinates.
pub const LAND_Y_OFFSET: f64 = -50.0;

/// Definition of a potential bonus landing pad on the lunar surface.
#[derive(Clone, Copy, Debug)]
pub struct ZoneDef {
    /// Index into the terrain segment array.
    pub line_num: usize,
    /// Score multiplier awarded for landing on this pad (`2`..=`5`).
    pub multiplier: u32,
}

